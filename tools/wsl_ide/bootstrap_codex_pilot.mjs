#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { resolve } from "node:path";

const repoUrl = "https://github.com/TeaShaman-cyber/theseus-local-lab.git";
const wslRepo = process.env.THESEUS_WSL_REPO || "/home/poklad/theseus-local-lab";
const wslHome = process.env.THESEUS_WSL_HOME || "/home/poklad";
const wslCodex = `${wslHome}/.local/bin/codex`;
const wslCodexHome = process.env.THESEUS_WSL_CODEX_HOME || `${wslHome}/.local/share/theseus-codex-pilot`;

function emit(event, detail = {}) {
  process.stdout.write(`${JSON.stringify({ event: "wsl_codex_pilot", stage: event, ...detail })}\n`);
}

function runWsl(script, timeout = 120_000) {
  const result = spawnSync("wsl.exe", ["-d", "Ubuntu-24.04", "--cd", wslHome, "--", "bash", "-c", script], {
    encoding: "utf8",
    timeout,
    windowsHide: true,
  });
  if (result.status !== 0) {
    throw new Error((result.stderr || result.stdout || "WSL command failed").trim());
  }
  return (result.stdout || "").trim();
}

function quote(value) {
  return `'${String(value).replaceAll("'", "'\\\"'\\\"'")}'`;
}

function profileToml() {
  return `# Generated by tools/wsl_ide/bootstrap_codex_pilot.mjs\n# WSL pilot only. Runtime state remains in Linux FS; no AutoMem credential is persisted here.\n\n[mcp_servers.mempalace]\nurl = \"http://127.0.0.1:18765/mcp\"\nenabled = true\nstartup_timeout_sec = 60\ntool_timeout_sec = 120\n\n[mcp_servers.theseus_docker]\ncommand = \"node\"\nargs = [\"${wslRepo}/tools/docker_control_plane/direct_bridge.mjs\"]\nenabled = true\nstartup_timeout_sec = 30\ntool_timeout_sec = 90\n\n[mcp_servers.theseus_docker.env]\nTHESEUS_PROJECT_ROOT = \"${wslRepo}\"\n\n# AutoMem is added by a separate process-local Infisical launcher.\n# Do not paste AUTOMEM_API_KEY into this profile.\n`;
}

function main() {
  const dryRun = process.argv.includes("--dry-run");
  const profilePath = `${wslCodexHome}/config.toml`;
  const localRepo = resolve(import.meta.dirname, "..", "..");
  if (!existsSync(localRepo)) throw new Error("workspace_not_found");

  emit("preflight", { wsl_repo: wslRepo, profile: profilePath, dry_run: dryRun });
  const existing = runWsl(`test -d ${quote(`${wslRepo}/.git`)} && echo existing || echo absent`, 20_000);
  if (dryRun) {
    emit("plan", { clone: existing === "absent", write_profile: profilePath, mempalace: "streamable-http" });
    return;
  }

  if (existing === "absent") {
    emit("clone", { repo: repoUrl, destination: wslRepo });
    runWsl(`git clone --origin origin ${quote(repoUrl)} ${quote(wslRepo)}`, 180_000);
  } else {
    emit("reuse_clone", { destination: wslRepo });
  }

  const encodedProfile = Buffer.from(profileToml(), "utf8").toString("base64");
  emit("write_profile", { profile: profilePath });
  runWsl(`mkdir -p ${quote(wslCodexHome)} && printf %s ${quote(encodedProfile)} | base64 -d > ${quote(profilePath)}`, 20_000);

  emit("verify", { profile: profilePath });
  runWsl(
    `test -x ${quote(wslCodex)} && test -f ${quote(profilePath)} && CODEX_HOME=${quote(wslCodexHome)} ${quote(wslCodex)} mcp get mempalace --json >/dev/null`,
    20_000,
  );
  emit("complete", {
    verification: "native_binary+native_code_home+http_mempalace_profile_present",
    agent_smoke: "requires WSL-native Codex login in the isolated CODEX_HOME; run wsl_pilot_smoke after authentication",
  });
}

try {
  main();
} catch (error) {
  emit("failed", { message: error.message });
  process.exitCode = 1;
}
