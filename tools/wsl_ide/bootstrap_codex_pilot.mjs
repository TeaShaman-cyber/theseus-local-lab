#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { resolve } from "node:path";

const repoUrl = "https://github.com/TeaShaman-cyber/theseus-local-lab.git";
const wslRepo = process.env.THESEUS_WSL_REPO || "/home/poklad/theseus-local-lab";
const wslHome = process.env.THESEUS_WSL_HOME || "/home/poklad";
const wslMcpCache = `${wslHome}/.cache/theseus-mcp/mcp-automem`;
const wslCodex = `${wslHome}/.local/bin/codex`;
const profileName = "theseus-pilot";

function emit(event, detail = {}) {
  process.stdout.write(`${JSON.stringify({ event: "wsl_codex_pilot", stage: event, ...detail })}\n`);
}

function runWsl(script, timeout = 120_000) {
  const result = spawnSync("wsl.exe", ["-d", "Ubuntu-24.04", "--cd", wslHome, "--", "bash", "-c", script], {
    encoding: "utf8",
    timeout,
    windowsHide: true,
  });
  if (result.status !== 0) {
    throw new Error((result.stderr || result.stdout || "WSL command failed").trim());
  }
  return (result.stdout || "").trim();
}

function quote(value) {
  return `'${String(value).replaceAll("'", "'\\\"'\\\"'")}'`;
}

function profileToml() {
  return `# Generated by tools/wsl_ide/bootstrap_codex_pilot.mjs\n# WSL pilot only. It intentionally does not persist AutoMem credentials.\n\n[mcp_servers.mempalace]\ncommand = \"docker\"\nargs = [\"run\", \"-i\", \"--rm\", \"-v\", \"theseus-mempalace-clean:/data\", \"theseus-mempalace:pilot\"]\nenabled = true\nstartup_timeout_sec = 60\ntool_timeout_sec = 120\n\n[mcp_servers.theseus_docker]\ncommand = \"node\"\nargs = [\"${wslRepo}/tools/docker_control_plane/direct_bridge.mjs\"]\nenabled = true\nstartup_timeout_sec = 30\ntool_timeout_sec = 90\n\n[mcp_servers.theseus_docker.env]\nTHESEUS_PROJECT_ROOT = \"${wslRepo}\"\n\n# AutoMem is added by a separate process-local Infisical launcher.\n# Do not paste AUTOMEM_API_KEY into this profile.\n`;
}

function main() {
  const dryRun = process.argv.includes("--dry-run");
  const profilePath = `${wslHome}/.codex/${profileName}.config.toml`;
  const localRepo = resolve(import.meta.dirname, "..", "..");
  if (!existsSync(localRepo)) throw new Error("workspace_not_found");

  emit("preflight", { wsl_repo: wslRepo, profile: profilePath, dry_run: dryRun });
  const existing = runWsl(`test -d ${quote(`${wslRepo}/.git`)} && echo existing || echo absent`, 20_000);
  if (dryRun) {
    emit("plan", { clone: existing === "absent", install_mcp_dependencies: true, write_profile: profilePath });
    return;
  }

  if (existing === "absent") {
    emit("clone", { repo: repoUrl, destination: wslRepo });
    runWsl(`git clone --origin origin ${quote(repoUrl)} ${quote(wslRepo)}`, 180_000);
  } else {
    emit("reuse_clone", { destination: wslRepo });
  }

  emit("install_mcp_dependencies", { package: "mcp-automem", cache: wslMcpCache });
  runWsl(
    `mkdir -p ${quote(wslMcpCache)} && cd ${quote(wslMcpCache)} && npm install --ignore-scripts --no-audit --no-fund @verygoodplugins/mcp-automem@0.15.0`,
    180_000,
  );

  const encodedProfile = Buffer.from(profileToml(), "utf8").toString("base64");
  emit("write_profile", { profile: profilePath });
  runWsl(`mkdir -p ${quote(`${wslHome}/.codex`)} && printf %s ${quote(encodedProfile)} | base64 -d > ${quote(profilePath)}`, 20_000);

  emit("verify", { profile: profilePath });
  const verification = runWsl(
    `test -x ${quote(wslCodex)} && test -f ${quote(profilePath)} && test -f ${quote(`${wslMcpCache}/node_modules/@verygoodplugins/mcp-automem/dist/index.js`)}`,
    20_000,
  );
  emit("complete", {
    verification: verification ? "native_binary+profile+package_present" : "present",
    agent_smoke: "requires WSL-native Codex login; run wsl_pilot_smoke after authentication",
  });
}

try {
  main();
} catch (error) {
  emit("failed", { message: error.message });
  process.exitCode = 1;
}
